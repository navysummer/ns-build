//! 编译/链接/归档命令生成。
//!
//! 只负责把目标描述转成具体的外部命令（gcc/clang/ar），执行交由 executor。

use std::path::{Path, PathBuf};

use crate::platform::Host;
use crate::script::{Profile, ResolvedTarget};

/// 一个可执行的任务单元（编译一个对象 / 链接 / 归档）。
#[derive(Debug, Clone)]
pub struct CompileTask {
    pub key: String,
    pub kind: CompileKind,
    /// 输入文件。
    pub inputs: Vec<PathBuf>,
    /// 依赖文件（仅编译任务）。
    pub depfile: Option<PathBuf>,
    /// 产物。
    pub output: PathBuf,
    /// 完整命令。
    pub command: Vec<String>,
    /// 是否允许并行。
    pub parallel: bool,
    pub label: String,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CompileKind {
    /// 单个源文件编译为 .o。
    Obj,
    /// unity build：多个源文件合并编译为一个 .o。
    UnityObj,
    /// 链接可执行/动态库。
    Link,
    /// 归档静态库。
    Archive,
    /// 纯命令（钩子）。
    Command,
}

/// 判断文件是否 C++ 源。
pub fn is_cxx(path: &Path) -> bool {
    matches!(
        path.extension().and_then(|s| s.to_str()),
        Some("cc") | Some("cpp") | Some("cxx") | Some("C") | Some("mm") | Some("mxx")
    )
}

/// 判断是否 C 源。
pub fn is_c_source(path: &Path) -> bool {
    matches!(
        path.extension().and_then(|s| s.to_str()),
        Some("c") | Some("m")
    )
}

/// 构建编译单源文件的命令。
pub fn compile_command(
    cc: &str,
    src: &Path,
    out: &Path,
    depfile: &Path,
    target: &ResolvedTarget,
    host: Host,
    profile: Profile,
    is_cxx: bool,
) -> Vec<String> {
    let mut cmd = vec![cc.to_string()];
    // 基础优化/调试。
    for f in profile.opt_flags() {
        cmd.push(f.to_string());
    }
    if target.strip {
        cmd.push("-s".into());
    }
    if is_cxx {
        cmd.push("-std=c++17".into());
        cmd.push("-fPIC".into());
    } else {
        cmd.push("-std=c11".into());
    }
    // 警告。
    if is_cxx {
        cmd.push("-Wall".into());
        cmd.push("-Wextra".into());
    } else {
        cmd.push("-Wall".into());
    }
    // 宏定义。
    for d in &target.defines {
        cmd.push(format!("-D{d}"));
    }
    // include 目录。
    for inc in &target.include_dirs {
        cmd.push(format!("-I{}", inc.display()));
    }
    // 编译标志（target + defaults）。
    for f in &target.flags {
        cmd.push(f.clone());
    }
    for f in &target.cflags {
        cmd.push(f.clone());
    }
    // 生成依赖文件 + 位置无关代码。
    cmd.push("-MMD".into());
    cmd.push("-MF".into());
    cmd.push(depfile.to_string_lossy().into_owned());
    cmd.push("-fPIC".into());
    cmd.push("-c".into());
    cmd.push(src.to_string_lossy().into_owned());
    cmd.push("-o".into());
    cmd.push(out.to_string_lossy().into_owned());
    let _ = host;
    cmd
}

/// unity build：将多个源文件合成一个合并单元（`#include` 全部源），
/// 编译为单个 `.o`，大幅减少编译启动开销。
pub fn unity_compile_command(
    cc: &str,
    srcs: &[PathBuf],
    unity_src: &Path,
    out: &Path,
    depfile: &Path,
    target: &ResolvedTarget,
    profile: Profile,
) -> Vec<String> {
    // 生成合并源文件：每个源 `#include "相对路径"`。
    // （由调用方生成，此处仅构建命令。）
    let _ = srcs;
    let mut cmd = vec![cc.to_string()];
    for f in profile.opt_flags() {
        cmd.push(f.to_string());
    }
    if target.strip {
        cmd.push("-s".into());
    }
    cmd.push("-std=c11".into());
    cmd.push("-Wall".into());
    for d in &target.defines {
        cmd.push(format!("-D{d}"));
    }
    for inc in &target.include_dirs {
        cmd.push(format!("-I{}", inc.display()));
    }
    for f in &target.flags {
        cmd.push(f.clone());
    }
    for f in &target.cflags {
        cmd.push(f.clone());
    }
    cmd.push("-MMD".into());
    cmd.push("-MF".into());
    cmd.push(depfile.to_string_lossy().into_owned());
    cmd.push("-fPIC".into());
    cmd.push("-c".into());
    cmd.push(unity_src.to_string_lossy().into_owned());
    cmd.push("-o".into());
    cmd.push(out.to_string_lossy().into_owned());
    cmd
}

/// 生成 unity 合并源文件内容。
pub fn unity_source_content(srcs: &[PathBuf]) -> String {
    let mut s = String::from("/* unity build generated by ns-build */\n");
    for src in srcs {
        let path = src.to_string_lossy().replace('\\', "/");
        s.push_str(&format!("#include \"{path}\"\n"));
    }
    s
}

/// 链接命令（可执行 / 动态库）。
pub fn link_command(
    target: &ResolvedTarget,
    objs: &[PathBuf],
    out: &Path,
    host: Host,
    profile: Profile,
) -> Vec<String> {
    let mut cmd = vec![target.cc.clone()];
    for f in profile.opt_flags() {
        cmd.push(f.to_string());
    }
    // 库搜索目录。
    for d in &target.link_dirs {
        cmd.push(format!("-L{}", d.display()));
    }
    for f in &target.flags {
        cmd.push(f.clone());
    }
    for f in &target.link_flags {
        cmd.push(f.clone());
    }
    for o in objs {
        cmd.push(o.to_string_lossy().into_owned());
    }
    for l in &target.link {
        // 已带路径或绝对路径直接用，否则 `-l`。
        if l.starts_with('/') || l.starts_with('.') || l.contains('/') {
            cmd.push(l.clone());
        } else {
            cmd.push(format!("-l{l}"));
        }
    }
    if target.strip {
        cmd.push("-s".into());
    }
    match target.kind {
        crate::script::TargetKind::Lib => {
            cmd.push("-shared".into());
            cmd.push("-o".into());
            cmd.push(out.to_string_lossy().into_owned());
            if host.os.is_windows_family() {
                // 导出全部符号（简化处理）。
                cmd.push("-Wl,--export-all-symbols".into());
            }
        }
        crate::script::TargetKind::Exe => {
            cmd.push("-o".into());
            cmd.push(out.to_string_lossy().into_owned());
        }
        _ => {
            cmd.push("-o".into());
            cmd.push(out.to_string_lossy().into_owned());
        }
    }
    cmd
}

/// 归档命令（静态库）。
pub fn archive_command(ar: &str, objs: &[PathBuf], out: &Path) -> Vec<String> {
    let mut cmd = vec![ar.to_string()];
    cmd.push("rcs".into());
    cmd.push(out.to_string_lossy().into_owned());
    for o in objs {
        cmd.push(o.to_string_lossy().into_owned());
    }
    cmd
}

/// 从目标 + 对象文件构建链接/归档任务。
pub fn make_link_task(
    target: &ResolvedTarget,
    objs: Vec<PathBuf>,
    host: Host,
    profile: Profile,
    ar: &str,
) -> CompileTask {
    let cmd = match target.kind {
        crate::script::TargetKind::Static => archive_command(ar, &objs, &target.output),
        _ => link_command(target, &objs, &target.output, host, profile),
    };
    CompileTask {
        key: format!("link:{}", target.name),
        kind: match target.kind {
            crate::script::TargetKind::Static => CompileKind::Archive,
            _ => CompileKind::Link,
        },
        inputs: objs,
        depfile: None,
        output: target.output.clone(),
        command: cmd,
        parallel: target.parallel,
        label: format!("LINK {}", target.name),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::script::TargetKind;

    fn target(name: &str, kind: TargetKind) -> ResolvedTarget {
        ResolvedTarget {
            name: name.into(),
            kind,
            cc: "cc".into(),
            sources: vec![],
            include_dirs: vec![],
            flags: vec![],
            cflags: vec![],
            cxxflags: vec![],
            link: vec![],
            link_dirs: vec![],
            link_flags: vec![],
            defines: vec![],
            deps: vec![],
            output: PathBuf::from(format!("out/{name}")),
            groups: None,
            group_size: None,
            parallel: true,
            hooks: Default::default(),
            profile: Profile::Release,
            strip: false,
            install: true,
        }
    }

    #[test]
    fn compile_has_depfile_and_pic() {
        let t = target("a", TargetKind::Exe);
        let cmd = compile_command(
            "gcc",
            Path::new("a.c"),
            Path::new("a.o"),
            Path::new("a.d"),
            &t,
            Host::current(),
            Profile::Release,
            false,
        );
        assert!(cmd.iter().any(|c| c == "-c"));
        assert!(cmd.iter().any(|c| c == "-MMD"));
        assert!(cmd.iter().any(|c| c.starts_with("-MF")));
        assert!(cmd.iter().any(|c| c == "-fPIC"));
    }

    #[test]
    fn link_exe_uses_o_flag() {
        let t = target("a", TargetKind::Exe);
        let cmd = link_command(&t, &[PathBuf::from("a.o")], &t.output, Host::current(), Profile::Release);
        assert_eq!(cmd[0], "cc");
        assert!(cmd.contains(&"a.o".to_string()));
        assert!(cmd.contains(&"-o".to_string()));
    }

    #[test]
    fn archive_uses_rcs() {
        let t = target("a", TargetKind::Static);
        let cmd = archive_command("ar", &[PathBuf::from("a.o")], &t.output);
        assert_eq!(cmd[0], "ar");
        assert_eq!(cmd[1], "rcs");
    }

    #[test]
    fn is_cxx_detects() {
        assert!(is_cxx(Path::new("a.cpp")));
        assert!(!is_cxx(Path::new("a.c")));
    }
}
